def _clean(o: Any) -> Any:
    if isinstance(o, dict):
        return {str(k): _clean(v) for k, v in o.items()}
    if isinstance(o, list | tuple):
        return [_clean(v) for v in o]
    if isinstance(o, np.bool_ | bool):
        return bool(o)
    if isinstance(o, np.integer | int):
        return int(o)
    if isinstance(o, np.floating | float):
        f = float(o)
        return f if math.isfinite(f) else None
    return o


def _dump(obj: Any, path: Path) -> None:
    path.write_text(json.dumps(_clean(obj), indent=2, sort_keys=True, allow_nan=False) + "\n")


def null_cos_tissue(
    truth: np.ndarray, pred: np.ndarray, tissue: np.ndarray
) -> tuple[float | None, int]:
    """Mean over TISSUE pixels of |cos| between the per-pixel error vector e = pred - truth (3 materials)
    and the F-014 null direction. Pixels with zero error (||e|| <= 1e-12) are excluded and counted out.
    Inputs (N, 3, H, W); tissue (N, H, W) bool. Returns (mean or None, number of pixels used).
    """
    e = np.moveaxis(np.asarray(pred, np.float64) - np.asarray(truth, np.float64), 1, -1)[tissue]
    nrm = np.linalg.norm(e, axis=1)
    keep = nrm > 1e-12
    if not keep.any():
        return None, 0
    cos = np.abs(e[keep] @ NULL_F014) / nrm[keep]
    return float(cos.mean()), int(keep.sum())


def mixed_voxel_frac(maps: np.ndarray, tissue: np.ndarray, thresh: float) -> float | None:
    """Fraction of TISSUE pixels whose largest material fraction is below `thresh` (default 0.9)."""
    p = np.moveaxis(np.asarray(maps, np.float64), 1, -1)[tissue]
    return float((p.max(axis=1) < thresh).mean()) if len(p) else None


def _regime_rmse(truth: np.ndarray, pred: np.ndarray, mask: np.ndarray) -> float | None:
    """sqrt(mean over masked pixels and 3 materials of (t - r)^2); None if the regime is empty."""
    if not mask.any():
        return None
    d2 = ((truth.astype(np.float64) - pred) ** 2).sum(axis=1)
    return float(np.sqrt(d2[mask].sum() / (3 * mask.sum())))


def evaluate(truth: np.ndarray, pred: np.ndarray, *, roi: int, thresh: float) -> dict[str, Any]:
    """Per-seed metrics on one split. Regimes come from the TRUTH sum (metrics.regime_masks)."""
    t = np.asarray(truth, np.float64)
    r = np.asarray(pred, np.float64)
    air, tissue, band = M.regime_masks(t, S.PARTITION_TOL)
    pm = M.per_material_errors(t, r)
    part = M.partition_errors(t, r, S.PARTITION_TOL)
    cos, n_cos = null_cos_tissue(t, r, tissue)
    return {
        "s1": M.s1_mean_rmse(t, r),
        "s2": M.s2_worst_roi_rmse(t, r, roi=roi),
        "per_material_rmse": {m: pm[m]["rmse"] for m in S.MATERIALS},
        "regime_rmse": {
            "air": _regime_rmse(t, r, air),
            "tissue": _regime_rmse(t, r, tissue),
            "band": _regime_rmse(t, r, band),
        },
        "regime_pixel_counts": {
            "air": int(air.sum()),
            "tissue": int(tissue.sum()),
            "band": int(band.sum()),
        },
        "null_cos_tissue": cos,
        "null_cos_n_pixels": n_cos,
        "mixed_voxel_frac": mixed_voxel_frac(r, tissue, thresh),
        "mixed_voxel_frac_truth_tissue": mixed_voxel_frac(t, tissue, thresh),
        "partition": {
            "tissue_mean_abs": part["tissue_mean_abs"],
            "air_mean_abs": part["air_mean_abs"],
        },
    }


def _flat(rec: dict[str, Any]) -> dict[str, float | None]:
    pm, rg = rec["per_material_rmse"], rec["regime_rmse"]
    return {
        "s1": rec["s1"], "s2": rec["s2"],
        "rmse_adipose": pm["adipose"], "rmse_fibroglandular": pm["fibroglandular"],
        "rmse_calcification": pm["calcification"],
        "rmse_air": rg["air"], "rmse_tissue": rg["tissue"], "rmse_band": rg["band"],
        "consistency_train": rec["consistency_train"], "consistency_val": rec["consistency_val"],
        "null_cos_tissue": rec["null_cos_tissue"], "mixed_voxel_frac": rec["mixed_voxel_frac"],
    }  # fmt: skip


def aggregate(recs: list[dict[str, Any]]) -> dict[str, Any]:
    """Across-seed mean, sample std (ddof=1), cv = std/|mean| for every flat metric. Single run:
    std and cv are null (not applicable)."""
    flats = [_flat(r) for r in recs]
    out: dict[str, Any] = {}
    for k in FLAT_KEYS:
        vals = np.array([f[k] for f in flats if f[k] is not None], np.float64)
        if vals.size == 0:
            out[k] = None
            continue
        mean = float(vals.mean())
        std = float(vals.std(ddof=1)) if vals.size > 1 else None
        cv = std / abs(mean) if std is not None and mean != 0 else None
        out[k] = {"mean": mean, "std": std, "cv": cv, "n": int(vals.size), "values": vals.tolist()}
    return out


def _tables(p: dict[str, Any]) -> dict[int, S.ModelTable]:
    table_dir = ROOT / str(p["table_dir"])
    return {k: S.load_model_table(table_dir / f"model_data_{k}kVp.npy", k) for k in S.KVPS}


def build_data(cfg: ExperimentConfig, tables: dict[int, S.ModelTable]) -> dict[str, Split]:
    """Train and validation splits only. The test split is never requested."""
    p = cfg.params
    sc = SyntheticConfig(
        n_cases=int(p["n_cases"]), n_pix=int(p["n_pix"]), n_views=int(p["n_views"]),
        n_det=int(p["n_det"]), seed=cfg.seed,
    )  # fmt: skip
    data = generate(sc, tables)
    fr = (float(p["f_train"]), float(p["f_val"]), float(p["f_test"]))
    meas = np.stack([data.images[S.KVP_LOW], data.images[S.KVP_HIGH]], axis=1).astype(np.float32)
    truth = data.phantoms.astype(np.float32)
    out = {}
    for name in ("train", "val"):
        idx = split_indices(sc.n_cases, cfg.seed, name, fractions=fr)  # type: ignore[arg-type]
        if idx.size == 0:
            raise ValueError(f"{name} split is empty; change n_cases or fractions")
        m, t = meas[idx], truth[idx]
        out[name] = Split(torch.from_numpy(m), torch.from_numpy(t), m, t)
    return out


def _train_learned(
    rung: dict[str, Any], seed: int, p: dict[str, Any], fwd: AapmTorchForward,
    tr: Split, va: Split,
) -> tuple[np.ndarray, float, float, dict[str, list[float]]]:  # fmt: skip
    """Returns (validation prediction, train consistency, val consistency, history). The label-free
    branch receives NO truth tensor: it passes only tr.meas / va.meas."""
    output = str(rung["output"])
    budget = {
        "epochs": int(p["epochs"]), "lr": float(p["lr"]),
        "batch_size": int(p["batch_size"]), "seed": seed,
    }  # fmt: skip

    def factory() -> UNet:
        return UNet(int(p["depth"]), int(p["width"]), output)

    if rung["kind"] == "supervised":
        model, hist = train_supervised(factory, tr.meas, tr.truth, va.meas, va.truth, **budget)
    else:
        weights = {"consistency_image": CONSISTENCY_WEIGHT}
        weights.update({t: float(p["prior_weight"]) for t in rung["priors"]})
        model, hist = train_label_free(
            factory, fwd, tr.meas, va.meas, weights, air_cutoff=float(p["air_cutoff"]), **budget
        )
    model.eval()
    with torch.no_grad():
        pred_va = model(va.meas)
        c_tr = float(consistency_image(model(tr.meas), tr.meas, fwd))
        c_va = float(consistency_image(pred_va, va.meas, fwd))
    return pred_va.numpy().astype(np.float64), c_tr, c_va, hist


def _run_rung(
    rung: dict[str, Any], seeds: list[int], p: dict[str, Any], tables: dict[int, S.ModelTable],
    fwd: AapmTorchForward, data: dict[str, Split], timing: dict[str, Any],
) -> tuple[dict[str, Any], dict[str, np.ndarray]]:  # fmt: skip
    """One rung: per-seed records (learned) or one deterministic record (classical)."""
    rid, va = rung["id"], data["val"]
    thresh = float(p["mixed_thresh"])
    roi = int(p["roi"])
    recs: dict[str, Any] = {}
    arrays: dict[str, np.ndarray] = {}
    runs = (
        [(f"seed{s}", s) for s in seeds] if rung["kind"] in LEARNED else [("deterministic", None)]
    )
    for key, seed in runs:
        t0 = time.perf_counter()
        hist: dict[str, list[float]] = {}
        if rung["kind"] == "classical":
            mu = C.effective_mu(tables)
            lo, hi = va.meas_np[:, 0], va.meas_np[:, 1]
            pred = C.decompose_lstsq(lo, hi, mu, mode=rung["mode"])
            c_tr = c_va = None
        elif rung["kind"] == "classical_tv":
            mu = C.effective_mu(tables)
            lo, hi = va.meas_np[:, 0], va.meas_np[:, 1]
            pred = C.decompose_tv(lo, hi, mu, lam=float(p["lam_tv"]), n_iter=int(p["tv_iters"]))
            c_tr = c_va = None
        else:
            pred, c_tr, c_va, hist = _train_learned(rung, int(seed), p, fwd, data["train"], va)
        timing.setdefault(rid, {})[key] = {"wall_s": time.perf_counter() - t0}
        if c_va is None:  # classical: report consistency of the classical prediction too
            pv = torch.from_numpy(np.asarray(pred, np.float32))
            c_va = float(consistency_image(pv, va.meas, fwd))
            c_tr = None
        rec = evaluate(va.truth_np, pred, roi=roi, thresh=thresh)
        rec["consistency_train"] = c_tr
        rec["consistency_val"] = c_va
        if hist:
            hk = "val_label_mse" if rung["kind"] == "supervised" else "val_consistency"
            rec["val_history"] = hist.get("val_consistency", [])
            rec["val_history_key"] = hk
        recs[key] = rec
        arrays[f"{rid}_{key}"] = np.asarray(pred, np.float32)
    body: dict[str, Any] = (
        {"per_seed": recs} if rung["kind"] in LEARNED else {"deterministic": recs}
    )
    rec_out = {
        "label": rid, "kind": rung["kind"], "uses_labels": bool(rung["uses_labels"]),
        "description": rung["desc"], **body,
        "aggregate": aggregate(list(recs.values())),
    }  # fmt: skip
    return rec_out, arrays


