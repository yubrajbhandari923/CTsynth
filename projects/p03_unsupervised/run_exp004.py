def _null_check(tables: dict[int, S.ModelTable]) -> float:
    """|cos| between the F-014 vector and the null vector of the kit's 2x3 effective-mu matrix."""
    _, _, vt = np.linalg.svd(C.effective_mu(tables))
    return float(abs(vt[-1] @ NULL_F014))


def _sha_inputs(cfg_path: Path, p: dict[str, Any]) -> list[dict[str, Any]]:
    files = [cfg_path] + [ROOT / str(p["table_dir"]) / f"model_data_{k}kVp.npy" for k in S.KVPS]
    files += [Path(__file__).resolve()] + sorted((ROOT / "src/ctsynth/aapm").glob("*.py"))
    return [
        {"path": str(f.resolve()), "bytes": f.stat().st_size, "sha256": sha256_file(f)}
        for f in files
    ]


